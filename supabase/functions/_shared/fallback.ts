// ============================================================
// fallback.ts — LLM生成に失敗したときの定型セリフ
//
// generateMessage() が（リトライしても）失敗したとき、半端な文や無言の
// 代わりにここの定型文を送る。
//
// 設計上の原則:
//   - Layer 3 の原則「状態に書かれていないことは言わない」を守る。
//     各セリフは対応する主訴のことだけに触れ、誇張・断定をしない。
//   - 実機の Complaint 型（8主訴）をすべて網羅する。1つでも欠けると
//     Record<Complaint, ...> が型エラーになる。
//   - 一人称を持たない口調にしてある。実機は amaenbo / tsundere / keigo の
//     複数キャラを character_id で切り替えるため、特定の一人称を書くと
//     別キャラに送ったときに口調が破綻する。フォールバックは「稀にしか
//     出ない安全網」なので、キャラ非依存の柔らかい定型で妥協する。
//
// なぜ emotion も見るか:
//   旧実装は complaint だけを引数に取っていた。しかし通知の発火条件は
//   (emotion, complaint) の変化であり、緊急度が境界をまたぐと complaint が
//   据え置きのまま emotion だけが変わって再通知される。complaint しか見ない
//   と、そのとき届く文面が毎回まったく同じ文字列になり、
//   「同じセリフが繰り返し届く」ように見えるうえ、通知が増えていること自体が
//   文面から読み取れなくなる。感情の強さで文面を変えて、少なくとも
//   「悪化して再通知された」ことが伝わるようにする。
// ============================================================

import { Complaint, Emotion } from "./emotionTable.ts";

/** 文面の強さ。感情ラダー（軽い不満 < 不満 < 不安 < 苛立ち）を2段に畳む */
type Tone = "mild" | "strong";

const TONE_BY_EMOTION: Record<Emotion, Tone> = {
  "満足": "mild",
  "軽い不満": "mild",
  "不満": "mild",
  "不安": "strong",
  "苛立ち": "strong",
};

/**
 * 主訴 × トーンごとの定型セリフ（キャラ非依存・柔らかめ）。
 * strong 側も「訴える強さ」を上げるだけで、確認できていない被害
 * （カビ・根腐れ・葉焼け）は断定しない。継続していることは匂わせてよい。
 */
const FALLBACK_LINES: Record<Complaint, Record<Tone, string>> = {
  "水分不足": {
    mild: "お水がほしいな…気づいてくれるとうれしいな",
    strong: "土がからからなの。そろそろお水をもらえないかな",
  },
  "水分過多": {
    mild: "お水がちょっと多いみたい。根っこが少し苦しいの",
    strong: "土がずっと濡れたままなの。すこし乾かしてほしいな",
  },
  "日照不足": {
    mild: "今日はおひさまが足りなかったの。明るいところに置いてほしいな",
    strong: "暗いところが続いているの。そろそろ日の当たる場所がいいな",
  },
  "日照過剰": {
    mild: "光がまぶしすぎるみたい。すこし日陰にしてほしいな",
    strong: "強い光がずっと当たっているの。日陰に移してほしいな",
  },
  "温度低すぎ": {
    mild: "すこし寒いよ…あたたかいところに連れていってほしいな",
    strong: "冷えたままなの。あたたかい場所に移してほしいな",
  },
  "温度高すぎ": {
    mild: "すこし暑いよ…すずしいところがいいな",
    strong: "暑いのがずっと続いているの。すずしい場所に移してほしいな",
  },
  "湿度低すぎ": {
    mild: "空気が乾いて葉先がかさかさするの。すこし潤いがほしいな",
    strong: "乾いた空気が続いているの。葉先までかさかさしてきたの",
  },
  "湿度高すぎ": {
    mild: "空気がじめじめして息苦しいの。風を通してほしいな",
    strong: "じめじめが続いていて息苦しいの。風を通してほしいな",
  },
};

/** 不調がないとき（満足）の定型セリフ */
const FALLBACK_SATISFIED = "今日はごきげんだよ。いつもありがとうね";

/**
 * 主訴と感情に対応する定型セリフを返す。
 * complaint が null（満足）のときは感情によらず満足時セリフを返す。
 * emotion 省略時は mild 扱い（旧シグネチャ互換）。
 */
export function fallbackMessage(
  complaint: Complaint | null,
  emotion?: Emotion | null,
): string {
  if (!complaint) return FALLBACK_SATISFIED;
  const tone = (emotion && TONE_BY_EMOTION[emotion]) ?? "mild";
  return FALLBACK_LINES[complaint][tone];
}
