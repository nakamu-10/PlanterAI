// ============================================================
// fallback.ts — LLM生成に失敗したときの定型セリフ
//
// generateMessage() が（リトライしても）打ち切り等で失敗したとき、
// 半端な文をユーザーに出す代わりにここの定型文を送る。
//
// 設計上の原則:
//   - Layer 3 の原則「状態に書かれていないことは言わない」を守る。
//     各セリフは対応する主訴のことだけに触れ、誇張・断定をしない。
//   - 実機の Complaint 型（8主訴）をすべて網羅する。1つでも欠けると
//     Record<Complaint, string> が型エラーになる。
//   - 一人称を持たない口調にしてある。実機は amaenbo / tsundere / keigo の
//     複数キャラを character_id で切り替えるため、特定の一人称を書くと
//     別キャラに送ったときに口調が破綻する。フォールバックは「稀にしか
//     出ない安全網」なので、キャラ非依存の柔らかい定型で妥協する。
// ============================================================

import { Complaint } from "./emotionTable.ts";

/** 主訴ごとの定型セリフ（キャラ非依存・柔らかめ） */
const FALLBACK_LINES: Record<Complaint, string> = {
  "水分不足": "お水がほしいな…気づいてくれるとうれしいな",
  "水分過多": "お水がちょっと多いみたい。根っこが少し苦しいの",
  "日照不足": "今日はおひさまが足りなかったの。明るいところに置いてほしいな",
  "日照過剰": "光がまぶしすぎるみたい。すこし日陰にしてほしいな",
  "温度低すぎ": "すこし寒いよ…あたたかいところに連れていってほしいな",
  "温度高すぎ": "すこし暑いよ…すずしいところがいいな",
  "湿度低すぎ": "空気が乾いて葉先がかさかさするの。すこし潤いがほしいな",
  "湿度高すぎ": "空気がじめじめして息苦しいの。風を通してほしいな",
};

/** 不調がないとき（満足）の定型セリフ */
const FALLBACK_SATISFIED = "今日はごきげんだよ。いつもありがとうね";

/**
 * 主訴に対応する定型セリフを返す。
 * complaint が null（満足）のときは満足時セリフを返す。
 */
export function fallbackMessage(complaint: Complaint | null): string {
  return complaint ? FALLBACK_LINES[complaint] : FALLBACK_SATISFIED;
}
